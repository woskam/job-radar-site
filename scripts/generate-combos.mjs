// Regenerates assets/combos.js and the city+category block of sitemap.xml:
// which /jobs/{city}/{category} pages exist. A combination only gets a page
// when it has enough live listings from enough different companies to be
// worth indexing, so the site doesn't fill up with thin near-empty pages.
//
// Usage: node scripts/generate-combos.mjs
//
// Reads through the site's own public /api/jobs relay (so no Hub key is
// needed locally), paging through each city once and counting categories
// locally: ~100 requests per run, instead of one per city x category pair.
// Re-run it every few weeks, or whenever locations.js changes.
import { readFileSync, writeFileSync } from "node:fs";
import { CATEGORIES } from "../assets/categories.js";
import { LOCATIONS } from "../assets/locations.js";

const SITE = "https://12getajob.com";
const MIN_LISTINGS = 20;
const MIN_COMPANIES = 3;
// No single company may make up more than this share of a combination's
// listings, or the page is really a one-company page ("Amsterdam AI & ML"
// was ~90% one employer when this was written).
const MAX_TOP_SHARE = 0.6;
const MAX_PER_CITY = 2000; // enough to qualify any category; the biggest cities hit this cap
// Category values too generic for anyone to search for ("tech jobs in
// Berlin" is just "jobs in Berlin").
const SKIP = new Set(["b2b", "consumer", "enterprise", "other", "resilience", "staffing", "tech"]);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function cityListings(city) {
  const all = [];
  for (let offset = 0; offset < MAX_PER_CITY; offset += 200) {
    const url = new URL("/api/jobs", SITE);
    url.searchParams.set("location_contains", city.slug.replace(/-/g, " "));
    url.searchParams.set("limit", "200");
    url.searchParams.set("offset", String(offset));
    const res = await fetch(url, { headers: { "User-Agent": "job-radar-site generate-combos" } });
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const { results } = await res.json();
    all.push(...results);
    if (results.length < 200) break;
    await sleep(300);
  }
  return all;
}

const combos = [];
for (const city of LOCATIONS) {
  if (city.slug === "remote") continue;
  const byCategory = new Map();
  for (const job of await cityListings(city)) {
    if (!CATEGORIES.includes(job.category) || SKIP.has(job.category)) continue;
    const entry = byCategory.get(job.category) || { listings: 0, companies: new Map() };
    entry.listings += 1;
    entry.companies.set(job.company, (entry.companies.get(job.company) || 0) + 1);
    byCategory.set(job.category, entry);
  }
  const qualifying = [...byCategory]
    .filter(([, e]) => e.listings >= MIN_LISTINGS && e.companies.size >= MIN_COMPANIES
      && Math.max(...e.companies.values()) / e.listings <= MAX_TOP_SHARE)
    .sort((a, b) => b[1].listings - a[1].listings);
  for (const [category, e] of qualifying) combos.push({ city: city.slug, category });
  console.log(`${city.slug}: ${qualifying.map(([c, e]) => `${c} (${e.listings}/${e.companies.size})`).join(", ") || "none"}`);
}

writeFileSync(new URL("../assets/combos.js", import.meta.url), `// GENERATED by scripts/generate-combos.mjs on ${new Date().toISOString().slice(0, 10)}, do not edit by hand.
// City + category combinations with at least ${MIN_LISTINGS} live listings from at least
// ${MIN_COMPANIES} companies, none of them more than ${MAX_TOP_SHARE * 100}% of the total. Each served at /jobs/{city}/{category}. Ordered by city
// (as in locations.js), then by listing count.
export const COMBOS = [
${combos.map((c) => `  { city: ${JSON.stringify(c.city)}, category: ${JSON.stringify(c.category)} },`).join("\n")}
];
`);

const START = "  <!-- city + category pages: generated by scripts/generate-combos.mjs -->";
const END = "  <!-- end city + category pages -->";
const sitemapPath = new URL("../sitemap.xml", import.meta.url);
let sitemap = readFileSync(sitemapPath, "utf8");
const block = [START, ...combos.map((c) => `  <url>
    <loc>${SITE}/jobs/${c.city}/${c.category}</loc>
    <changefreq>daily</changefreq>
    <priority>0.6</priority>
  </url>`), END].join("\n");
if (sitemap.includes(START)) {
  sitemap = sitemap.slice(0, sitemap.indexOf(START)) + block + sitemap.slice(sitemap.indexOf(END) + END.length);
} else {
  sitemap = sitemap.replace("</urlset>", `${block}\n</urlset>`);
}
writeFileSync(sitemapPath, sitemap);
console.log(`\n${combos.length} combinations written to assets/combos.js and sitemap.xml`);
